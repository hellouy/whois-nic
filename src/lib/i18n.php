 * - 语言来源优先级：?lang= 查询参数（写入 cookie） > cookie `lang` > Accept-Language 探测 > 默认 zh
 * - 提供 t() 取译文（支持 sprintf 占位）、te() 直接输出转义文本
 * - 提供 i18n_lang() / i18n_html_lang() / i18n_js_payload() 供模板与前端使用
 * - 不改动任何查询/解析逻辑，仅作用于界面文案
 */

